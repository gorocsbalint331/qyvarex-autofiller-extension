/**
 * Resolve helper-runtime bare npm specs from engine/extension node_modules,
 * esbuild-prebundle into a Parcel-compatible cache module.
 */
import fs from "node:fs"
import path from "node:path"
import { createRequire } from "node:module"
import { fileURLToPath } from "node:url"
import * as esbuild from "esbuild"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const EXT_ROOT = path.resolve(__dirname, "../..")
const REPO_ROOT = path.resolve(EXT_ROOT, "..")
const ENGINE_ROOT = path.join(REPO_ROOT, "engine")
const CACHE_DIR = path.join(__dirname, "../.npm-vendor-cache")

/** Alias leftover Parcel facade names → real npm package / subpath */
export const NPM_SPEC_ALIASES = {
  "react-reexport": "react",
  "react-dom-reexport": "react-dom",
  "zustand-react": "zustand",
  "zustand-vanilla": "zustand/vanilla",
}

/**
 * Packages we pull from node_modules instead of helper-runtime root facades.
 * Keys are linker specs after alias normalization.
 */
export const NPM_PACKAGE_SPECS = new Set([
  "react",
  "react/jsx-runtime",
  "react-dom",
  "react-dom/client",
  "antd",
  "@ant-design/cssinjs",
  "@ant-design/icons",
  "ahooks",
  "zustand",
  "zustand/vanilla",
  "classnames",
  "clsx",
  "crypto-js",
  "fuse.js",
  "lodash-es",
  "nanoid",
  "numeral",
  "pify",
  "tslib",
  "dataurl-to-blob",
  "react-draggable",
  "react-is",
  "react-lottie",
  "@plasmohq/messaging",
  "@plasmohq/storage",
  "@plasmohq/storage/hook",
  "@webext-core/match-patterns",
])

/** Shared peers left external so the linker graph has one React / dayjs / etc. */
const ALWAYS_EXTERNAL = new Set([
  "react",
  "react/jsx-runtime",
  "react-dom",
  "react-dom/client",
  "classnames",
  "dayjs",
  "@ant-design/cssinjs",
])

const requireFromEngine = createRequire(path.join(ENGINE_ROOT, "package.json"))
const requireFromExt = createRequire(path.join(EXT_ROOT, "package.json"))

/** Prefer browser-safe entry points when package default is Node-only. */
const ENTRY_OVERRIDES = {
  nanoid: "nanoid/non-secure",
}

const cacheMemo = new Map()

export function normalizeNpmSpec(specifier) {
  if (!specifier) return null
  if (NPM_SPEC_ALIASES[specifier]) return NPM_SPEC_ALIASES[specifier]
  if (NPM_PACKAGE_SPECS.has(specifier)) return specifier
  // dayjs plugins stay on SHIMS — not handled here
  if (specifier.startsWith("@ant-design/cssinjs/")) return "@ant-design/cssinjs"
  return null
}

export function isNpmVendorSpec(specifier) {
  return normalizeNpmSpec(specifier) != null
}

function resolvePackageEntry(spec) {
  const tryResolve = (req, name) => {
    try {
      return req.resolve(name)
    } catch {
      return null
    }
  }
  const override = ENTRY_OVERRIDES[spec]
  if (override) {
    return (
      tryResolve(requireFromEngine, override) ||
      tryResolve(requireFromExt, override) ||
      tryResolve(requireFromEngine, spec) ||
      tryResolve(requireFromExt, spec)
    )
  }
  return tryResolve(requireFromEngine, spec) || tryResolve(requireFromExt, spec)
}

function cacheFileName(spec) {
  return spec.replace(/[@/.]/g, "__") + ".js"
}

function rewriteExternals(body) {
  return body.replace(/require\(\s*["']([^"']+)["']\s*\)/g, (match, spec) => {
    let normalized = spec
    if (spec.startsWith("@ant-design/cssinjs")) {
      normalized = "@ant-design/cssinjs"
    }
    if (
      ALWAYS_EXTERNAL.has(normalized) ||
      NPM_PACKAGE_SPECS.has(normalized) ||
      normalized === "dayjs" ||
      normalized.startsWith("dayjs/")
    ) {
      return `__jrReq(${JSON.stringify(normalized)})`
    }
    return match
  })
}

function wrapParcelModule(spec, body, externals) {
  const depLines = [...externals]
    .sort()
    .map((d) => ` *   ${d} -> (npm)  =>  ${d}`)
    .join("\n")
  return `/**
 * npm-vendor-cache: ${spec}
 * Dependencies:
${depLines || " *   (none)"}
 *   @parcel/transformer-js/src/esmodule-helpers.js -> cHUbl  =>  @parcel/transformer-js/src/esmodule-helpers.js
 *
 * Generated by scripts/lib/npm-vendor-cache.mjs — do not hand-edit.
 */

var helpers = e("@parcel/transformer-js/src/esmodule-helpers.js")
helpers.defineInteropFlag(r)

var __jrReq = e

var __mod = (function () {
  var __cjsModule = { exports: {} }
  var module = __cjsModule
  var exports = __cjsModule.exports
${body}
  var out = module.exports
  return out
})()

if (__mod && typeof __mod === "object") {
  for (var __k in __mod) {
    if (Object.prototype.hasOwnProperty.call(__mod, __k)) r[__k] = __mod[__k]
  }
}
if (__mod && typeof __mod === "object" && "default" in __mod) {
  r.default = __mod.default
} else {
  r.default = __mod
}
`
}

function collectExternals(bundlingSpec) {
  const externals = new Set()
  for (const spec of ALWAYS_EXTERNAL) {
    if (spec !== bundlingSpec) externals.add(spec)
  }
  for (const spec of NPM_PACKAGE_SPECS) {
    if (spec !== bundlingSpec) externals.add(spec)
  }
  // dayjs plugins are shimmed separately
  externals.add("dayjs")
  return [...externals]
}

/**
 * Ensure a Parcel-loadable cached module exists for `spec` (already normalized).
 * Returns absolute path to the cache file.
 */
export function ensureNpmVendorModule(spec) {
  const normalized = normalizeNpmSpec(spec) || spec
  if (cacheMemo.has(normalized)) return cacheMemo.get(normalized)

  fs.mkdirSync(CACHE_DIR, { recursive: true })
  const outPath = path.join(CACHE_DIR, cacheFileName(normalized))

  const entry = resolvePackageEntry(normalized)
  if (!entry) {
    throw new Error(
      `[npm-vendor-cache] cannot resolve ${normalized} from engine or extension node_modules`,
    )
  }

  const tmpOut = path.join(CACHE_DIR, cacheFileName(normalized) + ".raw.cjs")
  const external = collectExternals(normalized)

  esbuild.buildSync({
    entryPoints: [entry],
    bundle: true,
    format: "cjs",
    platform: "browser",
    outfile: tmpOut,
    write: true,
    logLevel: "warning",
    external,
    define: {
      "process.env.NODE_ENV": '"production"',
    },
  })

  let raw = fs.readFileSync(tmpOut, "utf8").replace(/^"use strict";\s*/m, "")
  raw = rewriteExternals(raw)

  const usedExternals = new Set()
  for (const m of raw.matchAll(/__jrReq\(\s*["']([^"']+)["']\s*\)/g)) {
    usedExternals.add(m[1])
  }
  // Also mark dayjs plugin requires that esbuild left external
  for (const m of raw.matchAll(/require\(\s*["'](dayjs\/[^"']+)["']\s*\)/g)) {
    usedExternals.add(m[1])
  }
  raw = raw.replace(
    /require\(\s*["'](dayjs\/[^"']+)["']\s*\)/g,
    (__m, p) => `__jrReq(${JSON.stringify(p)})`,
  )
  for (const m of raw.matchAll(/__jrReq\(\s*["']([^"']+)["']\s*\)/g)) {
    usedExternals.add(m[1])
  }

  const wrapped = wrapParcelModule(normalized, raw, usedExternals)
  fs.writeFileSync(outPath, wrapped)
  try {
    fs.unlinkSync(tmpOut)
  } catch {
    /* ignore */
  }

  cacheMemo.set(normalized, outPath)
  return outPath
}
